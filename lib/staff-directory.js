// Full-name form: case, punctuation and "St." for Saint only — no filler words
// removed, so "Boston College" and "Boston University" stay two schools.
const fullKey = (s) =>
  String(s || '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/\bst\.?(?=\s)/g, 'saint')
    .replace(/[^a-z0-9]/g, '');

// Three lookups, tried in order: the full name, the shorter school key
// (lib/list-matches.js — "UNLV", "McNeese", "UC San Diego"), then the school
// key with a campus suffix removed. Each maps a key to every school that
// reduces to it. One school is an answer; two are an answer only when a state
// is known and picks exactly one ("Wheaton" is in Illinois and Massachusetts).
// Otherwise the lookup gives up — a link to the wrong school is worse than a
// search.
//
// Built once per set of schools: NCAA, NAIA and junior college, and all of
// them together for a name typed with no level. Keeping the sets apart means
// a level rules a school in or out before any name matching happens.
function makeIndex(rows) {
  const byFull = new Map();
  const byKey = new Map();
  const byCampusless = new Map();
  const byName = new Map();
  const add = (map, key, name) => {
    if (!key) return;
    if (!map.has(key)) map.set(key, new Set());
    map.get(key).add(name);
  };
  for (const row of rows) {
    const [name, state] = row;
    byName.set(name, row);
    const bare = name.replace(/\s*\([^)]*\)/g, '').trim();
    const paren = (name.match(/\(([^)]*)\)/) || [])[1] || '';
    for (const variant of [name, bare, paren && `${bare} ${paren}`, state && `${bare} ${state}`]) {
      if (variant) add(byFull, fullKey(variant), name);
    }
    add(byKey, schoolKey(name), name);
    // A campus or state suffix hides names like "Fairleigh Dickinson University,
    // Metropolitan Campus", "Montana State University-Bozeman" or "Kutztown
    // University of Pennsylvania". Its own map, tried last, so "University of
    // Maine, Farmington" never crowds out the University of Maine.
    const campusless = bare
      .replace(/\s*,.*$/, '')
      .replace(/-(?![^-]*\b(university|college|institute|academy)\b)[^-]{2,20}$/i, '')
      .replace(/\s+of (pennsylvania|new jersey)$/i, '')
      .trim();
    if (campusless && campusless !== bare) add(byCampusless, schoolKey(campusless), name);
  }
  return { byFull, byKey, byCampusless, byName };
}

const NCAA = makeIndex(DIRECTORIES);
const NON_NCAA = makeIndex(OTHER_DIRECTORIES);
const EVERY = makeIndex([...DIRECTORIES, ...OTHER_DIRECTORIES]);

// undefined: this map has nothing for the key, try the next one.
// null: it has schools but can't pick one — stop and search instead.
function pick(index, map, key, state) {
  const names = key && map.get(key);
  if (!names) return undefined;
  if (names.size === 1) return [...names][0];
  if (state) {
    const inState = [...names].filter((n) => index.byName.get(n)?.[1] === state);
    if (inState.length === 1) return inState[0];
  }
  return null;
}

// "Florida College" is not the University of Florida, though the short key
// makes them both "florida". When a name says college and the match says
// university (or the other way round), it is a different school.
const kindOf = (s) => {
  const v = String(s || '').toLowerCase();
  const college = /\bcolleges?\b/.test(v);
  const university = /\buniversity\b/.test(v);
  return college && !university ? 'college' : university && !college ? 'university' : '';
};
const sameKind = (typed, name) => {
  const a = kindOf(typed);
  const b = kindOf(name);
  return !a || !b || a === b;
};

function lookup(index, typed, state) {
  const urlOf = (name) => {
    const url = name ? index.byName.get(name)?.[2] : '';
    return url ? `https://${url}` : '';
  };
  const stateOf = (name) => index.byName.get(name)?.[1];
  // A known state that disagrees means a different school with a similar
  // name: Bethany College in Kansas is not Bethany College in West Virginia.
  const inState = (name) => !state || !stateOf(name) || stateOf(name) === state;
  const fk = fullKey(typed);
  // The exact official name is specific enough to trust over a state, which
  // the finder's own data occasionally gets wrong. A shortened form of it
  // ("Bethany College" for "Bethany College (West Virginia)") is not.
  // Not for NAIA and junior colleges, where the same name in two states is
  // common ("Bethel University", "Columbia College", "Highland Community
  // College") and the state is the only thing telling them apart.
  const full = pick(index, index.byFull, fk, state);
  const ncaaName = (n) => NCAA.byName.has(n);
  if (full !== undefined) return full && ((fullKey(full) === fk && ncaaName(full)) || inState(full)) ? urlOf(full) : '';
  // "Charleston" means the College of Charleston — unless the state says West
  // Virginia, in which case the keys below find the University of Charleston.
  // Short names are all NCAA schools, so they only apply where NCAA is in play.
  if (index !== NON_NCAA && SHORT_NAMES[fk] && index.byName.has(SHORT_NAMES[fk]) && inState(SHORT_NAMES[fk])) {
    return urlOf(SHORT_NAMES[fk]);
  }
  const key = schoolKey(typed);
  let name = pick(index, index.byKey, key, state);
  if (name === undefined) name = pick(index, index.byCampusless, key, state);
  if (!name || !sameKind(typed, name) || !inState(name)) return '';
  return urlOf(name);
}

/**
 * The staff directory URL for a school name as typed, or '' when unknown or
 * ambiguous. Both options are for ruling schools out, never in: `state` (two
 * letters) picks between schools sharing a name and rejects a match in another
 * state; `level` narrows the schools searched — D1–D3 to NCAA, NAIA or JUCO to
 * those, Club/Other to nothing.
 */
export function staffDirectoryFor(school, { state = '', level = '' } = {}) {
  const typed = String(school || '').trim();
  if (!typed) return '';
  const lv = String(level || '').trim();
  const index = !lv ? EVERY : /^D[123]$/.test(lv) ? NCAA : /^(NAIA|JUCO)$/.test(lv) ? NON_NCAA : null;
  if (!index) return '';
  const st = String(state || '').trim().toUpperCase();
  const direct = lookup(index, typed, st);
  if (direct) return direct;
  // "SUNY Cortland" is the State University of New York at Cortland.
  if (/^suny\s+/i.test(typed)) return lookup(index, typed.replace(/^suny\s+/i, 'State University of New York at '), st);
  // "RIT (Rochester Institute of Technology)": the finder puts the full name
  // in brackets after the short one.
  const inside = (typed.match(/\(([^)]{6,})\)/) || [])[1];
  if (inside) return lookup(index, inside, st);
  // Federal (EADA) names, which the College Finder uses for most sports, add a
  // campus: "Ohio State University-Main Campus", "University of Washington-
  // Seattle Campus", "Kent State University at Kent".
  // Only suffixes that name a campus, never another school: "Indiana
  // University-East" is not Indiana University.
  const campusless = typed
    .replace(/\s*-\s*[^-]*\bcampus$/i, '')
    .replace(/\s+(main campus|campus immersion)$/i, '')
    .replace(/\s+at\s+(\S+)$/i, (m, place) => (new RegExp(`\\b${place}\\b`, 'i').test(typed.slice(0, -m.length)) ? '' : m))
    .trim();
  return campusless && campusless !== typed ? lookup(index, campusless, st) : '';
}

