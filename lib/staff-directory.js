// NAIA and junior colleges live in lib/staff-directory-other.js, gathered a
// different way (neither association publishes a usable member list). For any
// school not matched, the app offers a search instead.
//
// Rows are [official NCAA name, state, directory URL without https://]. A row
// with no URL is an NCAA school whose directory could not be confirmed; it is
// kept so a name it shares with another school still counts as ambiguous —
